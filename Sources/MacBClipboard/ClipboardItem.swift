import AppKit
import CryptoKit
import ImageIO

extension ClipboardFeature {
    /// 내용을 복사한 앱(기록 시점에 맨 앞에 있던 앱).
    public struct SourceApp: Codable, Equatable, Sendable {
        public var name: String?
        public var bundleID: String?

        public init(name: String?, bundleID: String?) {
            self.name = name
            self.bundleID = bundleID
        }
    }

    /// 기록 또는 슬롯 항목 하나의 표시용 정보. 실제 바이트는 저장소가 따로 들고 있다.
    public struct Item: Codable, Equatable, Sendable, Identifiable {
        public enum Kind: String, Codable, Sendable {
            case text
            case image
            case files
        }

        public internal(set) var id: UUID
        public internal(set) var kind: Kind
        /// 검색·미리보기용 글자(앞부분 `textLimit`자까지). 파일은 이름을 줄바꿈으로 이은 것, 이미지는 빈 문자열.
        public internal(set) var text: String
        public internal(set) var fileNames: [String]
        /// 이미지의 픽셀 크기.
        public internal(set) var imagePixelSize: CGSize?
        public internal(set) var date: Date
        public internal(set) var sourceApp: SourceApp?
        /// 저장한 표현들의 바이트 합.
        public internal(set) var byteCount: Int

        /// 같은 내용인지 가리는 값(중복 제거용).
        var fingerprint: String
        var filePaths: [String]
        /// 목록에 그릴 작은 썸네일(PNG).
        var thumbnailPNG: Data?

        /// 색인 파일이 커지지 않도록 글자는 앞부분만 들고 있는다.
        static let textLimit = 4000
    }
}

// MARK: - Display

extension ClipboardFeature.Item {
    /// 목록에 보여 줄 미리보기. 공백과 줄바꿈은 하나로 접어 두 줄 안에 최대한 담는다.
    var previewText: String {
        switch kind {
        case .text:
            return String(text.prefix(400))
                .split(whereSeparator: { $0.isWhitespace })
                .joined(separator: " ")
        case .image:
            guard let size = imagePixelSize else { return "이미지" }
            return "이미지 · \(Int(size.width)) × \(Int(size.height))"
        case .files:
            return fileNames.joined(separator: ", ")
        }
    }

    /// 토스트 둘째 줄에 넣을 짧은 미리보기.
    var shortPreview: String {
        let preview = previewText
        guard preview.count > 40 else { return preview }
        return String(preview.prefix(40)) + "…"
    }

    /// 검색어를 공백으로 나눠 모두 들어 있는 항목만 남긴다(대소문자·전각 무시).
    static func filter(_ items: [Self], query: String) -> [Self] {
        let tokens = query.split(whereSeparator: { $0.isWhitespace }).map(String.init)
        guard !tokens.isEmpty else { return items }
        let options: String.CompareOptions = [.caseInsensitive, .diacriticInsensitive, .widthInsensitive]
        return items.filter { item in
            tokens.allSatisfy { item.text.range(of: $0, options: options) != nil }
        }
    }
}

// MARK: - Payload

/// 페이스트보드 내용의 사본. 항목(`NSPasteboardItem`)마다 표현(타입 + 바이트)을 원래 순서대로 담는다.
/// 순서를 지키는 이유: 받는 앱이 첫 타입을 가장 좋은 표현으로 보는 경우가 있다.
struct Payload: Codable, Equatable, Sendable {
    struct Representation: Codable, Equatable, Sendable {
        var type: String
        var data: Data
    }

    var items: [[Representation]]

    static let plainTextType = NSPasteboard.PasteboardType.string.rawValue
    static let rtfType = NSPasteboard.PasteboardType.rtf.rawValue
    static let rtfdType = NSPasteboard.PasteboardType.rtfd.rawValue
    static let htmlType = NSPasteboard.PasteboardType.html.rawValue
    static let pngType = NSPasteboard.PasteboardType.png.rawValue
    static let tiffType = NSPasteboard.PasteboardType.tiff.rawValue
    static let jpegType = "public.jpeg"
    static let fileURLType = NSPasteboard.PasteboardType.fileURL.rawValue
    static let urlType = NSPasteboard.PasteboardType.URL.rawValue

    /// 저장하는 표준 타입. 앱 전용 타입은 버린다(크기도 크고 다른 앱에선 못 쓴다).
    static let storedTypes: Set<String> = [
        plainTextType, rtfType, rtfdType, htmlType, pngType, tiffType, jpegType, fileURLType, urlType,
    ]

    /// 암호 관리자 등이 "기록하지 말 것"이라고 붙이는 표시(nspasteboard.org 관례 + 널리 쓰이는 옛 표시).
    static let doNotRecordMarkers: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "de.petermaurer.TransientPasteboardType",
        "com.agilebits.onepassword",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
    ]

    /// 내용을 올린 앱이 스스로 밝히는 번들 ID(nspasteboard.org 관례).
    static let sourceMarker = NSPasteboard.PasteboardType("org.nspasteboard.source")

    /// 항목 하나에 저장하는 최대 바이트. 큰 이미지 하나가 메모리·디스크를 잡아먹지 않게 한다.
    static let byteLimit = 16 * 1024 * 1024

    enum ReadResult {
        case empty
        case doNotRecord
        case tooLarge
        case contents(Payload, declaredSource: String?)
    }

    var byteCount: Int {
        items.reduce(0) { total, reps in reps.reduce(total) { $0 + $1.data.count } }
    }

    // MARK: Pasteboard I/O

    static func read(from pasteboard: NSPasteboard) -> ReadResult {
        guard let pasteboardItems = pasteboard.pasteboardItems, !pasteboardItems.isEmpty else { return .empty }

        var allTypes = Set((pasteboard.types ?? []).map(\.rawValue))
        for item in pasteboardItems { allTypes.formUnion(item.types.map(\.rawValue)) }
        if !allTypes.isDisjoint(with: doNotRecordMarkers) { return .doNotRecord }

        var items: [[Representation]] = []
        for pasteboardItem in pasteboardItems {
            var reps: [Representation] = []
            for type in pasteboardItem.types where storedTypes.contains(type.rawValue) {
                guard let data = pasteboardItem.data(forType: type), !data.isEmpty else { continue }
                reps.append(Representation(type: type.rawValue, data: data))
            }
            if !reps.isEmpty { items.append(reps) }
        }
        var payload = Payload(items: items)
        guard !payload.items.isEmpty else { return .empty }
        if payload.byteCount > byteLimit { payload.shrinkToLimit() }
        guard payload.byteCount <= byteLimit else { return .tooLarge }

        let source = pasteboard.string(forType: sourceMarker)
        return .contents(payload, declaredSource: source)
    }

    @discardableResult
    func write(to pasteboard: NSPasteboard) -> Bool {
        pasteboard.clearContents()
        let objects: [NSPasteboardItem] = items.map { reps in
            let item = NSPasteboardItem()
            for rep in reps {
                item.setData(rep.data, forType: NSPasteboard.PasteboardType(rep.type))
            }
            return item
        }
        return pasteboard.writeObjects(objects)
    }

    /// 용량을 넘으면 다른 표현으로 대신할 수 있는 것부터 버린다.
    /// 화면 캡처처럼 PNG와 거대한 TIFF를 함께 올리는 경우를 통째로 놓치지 않기 위해서다.
    private mutating func shrinkToLimit() {
        let stages: [(Set<String>) -> Set<String>] = [
            // 같은 그림의 무압축판, 같은 서식의 그림 포함판.
            { types in
                var drop: Set<String> = []
                if types.contains(Self.pngType) || types.contains(Self.jpegType) { drop.insert(Self.tiffType) }
                if types.contains(Self.rtfType) { drop.insert(Self.rtfdType) }
                return drop
            },
            // 글자가 있는 항목에 덧붙은 그림(엑셀 셀 그림 등).
            { types in
                types.contains(Self.plainTextType) ? [Self.pngType, Self.tiffType, Self.jpegType] : []
            },
        ]
        for stage in stages where byteCount > Self.byteLimit {
            items = items
                .map { reps in
                    let drop = stage(Set(reps.map(\.type)))
                    return reps.filter { !drop.contains($0.type) }
                }
                .filter { !$0.isEmpty }
        }
    }

    // MARK: Interpretation

    private func firstData(of type: String) -> Data? {
        for reps in items {
            if let rep = reps.first(where: { $0.type == type }) { return rep.data }
        }
        return nil
    }

    var plainText: String? {
        let parts = items.compactMap { reps in
            reps.first { $0.type == Self.plainTextType }.flatMap { String(data: $0.data, encoding: .utf8) }
        }
        return parts.isEmpty ? nil : parts.joined(separator: "\n")
    }

    /// 일반 글자가 없을 때 서식 있는 표현에서 글자를 뽑는다.
    private var richTextFallback: String? {
        if let rtf = firstData(of: Self.rtfType), let text = NSAttributedString(rtf: rtf, documentAttributes: nil)?.string {
            return text
        }
        if let rtfd = firstData(of: Self.rtfdType), let text = NSAttributedString(rtfd: rtfd, documentAttributes: nil)?.string {
            return text
        }
        if let html = firstData(of: Self.htmlType) {
            // WebKit을 띄우지 않으려고 태그만 걷어 낸다. 미리보기·검색용이라 이 정도면 된다.
            return String(decoding: html, as: UTF8.self)
                .replacingOccurrences(of: "<[^>]+>", with: " ", options: .regularExpression)
                .replacingOccurrences(of: "&nbsp;", with: " ")
                .replacingOccurrences(of: "&lt;", with: "<")
                .replacingOccurrences(of: "&gt;", with: ">")
                .replacingOccurrences(of: "&quot;", with: "\"")
                .replacingOccurrences(of: "&#39;", with: "'")
                .replacingOccurrences(of: "&amp;", with: "&")
        }
        if let url = firstData(of: Self.urlType) {
            return String(decoding: url, as: UTF8.self)
        }
        return nil
    }

    var fileURLs: [URL] {
        items.compactMap { reps in
            guard let rep = reps.first(where: { $0.type == Self.fileURLType }) else { return nil }
            let string = String(decoding: rep.data, as: UTF8.self)
                .trimmingCharacters(in: CharacterSet.whitespacesAndNewlines.union(.controlCharacters))
            guard let url = URL(string: string), url.isFileURL else { return nil }
            // Finder는 file:///.file/id=… 형태의 참조 URL을 올린다. 이름을 보여 주려면 경로로 풀어야 한다.
            return (url as NSURL).filePathURL ?? url
        }
    }

    private var imageData: Data? {
        firstData(of: Self.pngType) ?? firstData(of: Self.jpegType) ?? firstData(of: Self.tiffType)
    }

    private static func hasVisibleText(_ text: String) -> Bool {
        !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
    }

    /// 표시용 정보를 만든다. 보여 줄 게 없으면(빈 글자 등) nil.
    func makeItem(id: UUID = UUID(), date: Date, source: ClipboardFeature.SourceApp?) -> ClipboardFeature.Item? {
        var hasher = SHA256()
        func feed(_ string: String) { hasher.update(data: Data(string.utf8)) }

        let kind: ClipboardFeature.Item.Kind
        var text = ""
        var fileNames: [String] = []
        var filePaths: [String] = []
        var pixelSize: CGSize?
        var thumbnail: Data?

        let urls = fileURLs
        if !urls.isEmpty {
            kind = .files
            filePaths = urls.map(\.path)
            fileNames = urls.map { $0.lastPathComponent }
            text = fileNames.joined(separator: "\n")
            feed("files")
            for url in urls { feed(url.absoluteString + "\n") }
        } else if let plain = plainText, Self.hasVisibleText(plain) {
            // 같은 글자는 서식이 달라도 같은 항목으로 본다(보기에 똑같은 줄이 둘 생기지 않게).
            kind = .text
            text = plain
            feed("text")
            feed(plain)
        } else if let image = imageData {
            kind = .image
            pixelSize = ImageInfo.pixelSize(of: image)
            thumbnail = ImageInfo.thumbnailPNG(of: image)
            feed("data")
            for reps in items {
                for rep in reps {
                    feed(rep.type)
                    hasher.update(data: rep.data)
                }
                feed("|")
            }
        } else if let fallback = richTextFallback, Self.hasVisibleText(fallback) {
            kind = .text
            text = fallback
            feed("text")
            feed(fallback)
        } else {
            return nil
        }

        let fingerprint = hasher.finalize().map { String(format: "%02x", $0) }.joined()
        return ClipboardFeature.Item(
            id: id,
            kind: kind,
            text: String(text.prefix(ClipboardFeature.Item.textLimit)),
            fileNames: fileNames,
            imagePixelSize: pixelSize,
            date: date,
            sourceApp: source,
            byteCount: byteCount,
            fingerprint: fingerprint,
            filePaths: filePaths,
            thumbnailPNG: thumbnail
        )
    }
}

// MARK: - Images

enum ImageInfo {
    /// 헤더만 읽어 픽셀 크기를 얻는다(전체 디코딩 없이).
    static func pixelSize(of data: Data) -> CGSize? {
        guard
            let source = CGImageSourceCreateWithData(data as CFData, nil),
            let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
            let width = properties[kCGImagePropertyPixelWidth] as? Int,
            let height = properties[kCGImagePropertyPixelHeight] as? Int
        else { return nil }
        return CGSize(width: width, height: height)
    }

    static func thumbnailPNG(of data: Data, maxPixelSize: Int = 128) -> Data? {
        guard let source = CGImageSourceCreateWithData(data as CFData, nil) else { return nil }
        let options: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceCreateThumbnailWithTransform: true,
            kCGImageSourceThumbnailMaxPixelSize: maxPixelSize,
        ]
        guard let image = CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary) else { return nil }
        return NSBitmapImageRep(cgImage: image).representation(using: .png, properties: [:])
    }
}
